#!/usr/bin/env node
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const projectRoot = process.cwd()

const USER_PATH_RE = /\/Users\/[A-Za-z0-9._-]+(?:\/[A-Za-z0-9._-]+)*/g
const HOME_PATH_RE = /\/home\/[A-Za-z0-9._-]+(?:\/[A-Za-z0-9._-]+)*/g
const BEARER_RE = /Bearer\s+[A-Za-z0-9._-]{8,}/gi
const SECRET_RE = /\b(?:sk-[A-Za-z0-9_-]{16,}|xox[abp]-[A-Za-z0-9-]{10,}|ghp_[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|AIza[0-9A-Za-z_-]{30,})\b/g
const ENV_RE = /(API_KEY|TOKEN|SECRET|PASSWORD|PASSCODE|ACCESS_KEY|SESSION_KEY)=([^\s"']+)/gi
const AUTH_FILE_RE = /\b(?:auth\.json|\.env(?:\.[A-Za-z0-9_-]+)?|credentials\.json)\b/gi

export function hasUnsafeRestartProofText(value) {
  const text = String(value || '')
  return USER_PATH_RE.test(text) ||
    HOME_PATH_RE.test(text) ||
    BEARER_RE.test(text) ||
    SECRET_RE.test(text) ||
    ENV_RE.test(text) ||
    AUTH_FILE_RE.test(text)
}

export function isLocalOnlyBaseUrl(value) {
  try {
    const url = new URL(value)
    return url.protocol === 'http:' && (url.hostname === '127.0.0.1' || url.hostname === 'localhost' || url.hostname === '::1')
  } catch {
    return false
  }
}

function run(command, args, options = {}) {
  try {
    return execFileSync(command, args, {
      cwd: projectRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 5 * 1024 * 1024,
      ...options,
    }).trim()
  } catch {
    return ''
  }
}

function listenerPids(port) {
  const output = run('bash', ['-lc', `if command -v lsof >/dev/null 2>&1; then lsof -nP -tiTCP:${port} -sTCP:LISTEN || true; fi`])
  return output.split(/\s+/).filter((pid) => /^[0-9]+$/.test(pid))
}

function safeCookieName(value) {
  const cookieName = String(value || '').trim()
  return /^[A-Za-z0-9_.-]+$/.test(cookieName) ? cookieName : 'mc-session'
}

function readAutoGeneratedApiKey() {
  const file = join(projectRoot, '.next/standalone/.data/.auto-generated')
  if (!existsSync(file)) return ''
  const raw = readFileSync(file, 'utf8')
  const match = raw.match(/^API_KEY=(.+)$/m)
  return match?.[1]?.trim() || ''
}

function readSourceApiKey() {
  return run('sqlite3', [
    '.data/mission-control.db',
    "SELECT value FROM settings WHERE key='security.api_key' LIMIT 1;",
  ])
}

async function fetchText(baseUrl, path, options = {}) {
  try {
    const response = await fetch(`${baseUrl}${path}`, {
      method: 'GET',
      redirect: 'manual',
      cache: 'no-store',
      signal: AbortSignal.timeout(options.timeoutMs || 10_000),
      headers: options.headers || undefined,
    })
    const body = await response.text()
    return {
      status: response.status,
      location: response.headers.get('location'),
      content_type: response.headers.get('content-type'),
      body_bytes: body.length,
      unsafe_text_detected: hasUnsafeRestartProofText(body),
      body,
    }
  } catch (error) {
    return {
      status: 0,
      location: null,
      content_type: null,
      body_bytes: 0,
      unsafe_text_detected: false,
      error: error instanceof Error ? error.message.slice(0, 160) : 'request_failed',
      body: '',
    }
  }
}

function parseJsonProbe(probe) {
  try {
    return probe.body ? JSON.parse(probe.body) : null
  } catch {
    return null
  }
}

function projectReportFields({ baseUrl, beforePid, afterPid, listenerPids: pids, sourceCommit, sourceBranch, apiAuthConfigured, login, runtimePayload, failurePayload }) {
  return {
    checked_at: new Date().toISOString(),
    base_url: baseUrl,
    source_commit: sourceCommit,
    source_branch: sourceBranch,
    before_pid: beforePid || null,
    after_pid: afterPid || null,
    listener_pids: pids,
    api_auth_configured: apiAuthConfigured,
    login_probe: {
      status: login.status,
      mission_control_present: login.body.includes('Mission Control'),
      unsafe_text_detected: login.unsafe_text_detected,
    },
    runtime_health_probe: {
      status: runtimePayload.status,
      payload_ok: runtimePayload.payload?.ok === true,
      runtime_status: runtimePayload.payload?.status || null,
      bind_expected_host: runtimePayload.payload?.bind?.expected_host || null,
      no_public_exposure_added: runtimePayload.payload?.bind?.no_public_exposure_added === true,
      unsafe_text_detected: runtimePayload.unsafe_text_detected,
    },
    failure_states_probe: {
      status: failurePayload.status,
      payload_ok: failurePayload.payload?.ok === true,
      no_fake_live_status: failurePayload.payload?.no_fake_live_status === true,
      no_external_writes_executed: failurePayload.payload?.no_external_writes_executed === true,
      unsafe_text_detected: failurePayload.unsafe_text_detected,
    },
  }
}

export function buildRestartProofReport(input) {
  const failures = []
  const rollback = `git revert <day-71-restart-proof-commit-sha> && MC_HOSTNAME=127.0.0.1 PORT=${new URL(input.base_url).port || '3337'} bash scripts/start-standalone.sh`

  if (!isLocalOnlyBaseUrl(input.base_url)) {
    failures.push({ check: 'local_only_base_url', error: 'base_url_not_local_only' })
  }
  if (!input.after_pid) {
    failures.push({ check: 'after_pid', error: 'listener_pid_missing_after_restart' })
  }
  if (input.before_pid && input.after_pid && input.before_pid === input.after_pid) {
    failures.push({ check: 'pid_changed', error: 'restart_pid_did_not_change' })
  }
  if (!Array.isArray(input.listener_pids) || !input.after_pid || !input.listener_pids.includes(input.after_pid)) {
    failures.push({ check: 'listener_pids', error: 'after_pid_not_listening' })
  }
  if (!input.api_auth_configured) {
    failures.push({ check: 'api_auth', error: 'api_auth_not_configured_for_restart_proof' })
  }
  if (input.login_probe?.status !== 200 || input.login_probe?.mission_control_present !== true) {
    failures.push({ check: 'login', error: 'login_probe_failed', status: input.login_probe?.status ?? null })
  }
  if (input.runtime_health_probe?.status !== 200 || input.runtime_health_probe?.payload_ok !== true || input.runtime_health_probe?.runtime_status !== 'LIVE') {
    failures.push({ check: 'runtime_health', error: 'runtime_health_not_live', status: input.runtime_health_probe?.status ?? null })
  }
  if (input.runtime_health_probe?.bind_expected_host !== '127.0.0.1' || input.runtime_health_probe?.no_public_exposure_added !== true) {
    failures.push({ check: 'bind', error: 'local_bind_not_proven' })
  }
  if (input.failure_states_probe?.status !== 200 || input.failure_states_probe?.payload_ok !== true) {
    failures.push({ check: 'failure_states', error: 'failure_states_probe_failed', status: input.failure_states_probe?.status ?? null })
  }
  if (input.failure_states_probe?.no_fake_live_status !== true || input.failure_states_probe?.no_external_writes_executed !== true) {
    failures.push({ check: 'failure_states_safety', error: 'failure_states_safety_flags_missing' })
  }
  if (input.login_probe?.unsafe_text_detected || input.runtime_health_probe?.unsafe_text_detected || input.failure_states_probe?.unsafe_text_detected) {
    failures.push({ check: 'unsafe_text', error: 'unsafe_text_detected' })
  }

  return {
    ok: failures.length === 0,
    checked_at: input.checked_at,
    mode: 'production_restart_proof',
    blocker_class: failures.length ? 'BLOCKED' : 'NONE',
    source_commit: input.source_commit,
    source_branch: input.source_branch,
    base_url: input.base_url,
    no_public_exposure_added: true,
    secrets_printed: false,
    before_pid: input.before_pid || null,
    after_pid: input.after_pid || null,
    listener_pids: input.listener_pids || [],
    probes: {
      login: input.login_probe,
      runtime_health: input.runtime_health_probe,
      failure_states: input.failure_states_probe,
    },
    failures,
    rollback,
  }
}

async function runCli() {
  const baseUrl = (process.argv[2] || process.env.MISSION_CONTROL_BASE_URL || 'http://127.0.0.1:3337').replace(/\/+$/, '')
  const beforePid = process.env.RESTART_PROOF_BEFORE_PID || ''
  const parsed = new URL(baseUrl)
  const port = parsed.port || '3337'
  const pids = listenerPids(port)
  const afterPid = pids[0] || ''
  const apiKey = (process.env.MISSION_CONTROL_API_KEY || process.env.API_KEY || readAutoGeneratedApiKey() || readSourceApiKey()).trim()
  const cookieName = safeCookieName(process.env.MC_PROOF_COOKIE_NAME || 'mc-session')
  const headers = apiKey
    ? { 'x-api-key': apiKey, cookie: `${cookieName}=runtime-smoke-proxy-pass` }
    : undefined

  const login = await fetchText(baseUrl, '/login')
  const runtimeHealth = await fetchText(baseUrl, '/api/runtime/health', { headers })
  const failureStates = await fetchText(baseUrl, '/api/runtime/failure-states', { headers })
  const runtimePayload = {
    ...runtimeHealth,
    payload: parseJsonProbe(runtimeHealth),
  }
  const failurePayload = {
    ...failureStates,
    payload: parseJsonProbe(failureStates),
  }

  const input = projectReportFields({
    baseUrl,
    beforePid,
    afterPid,
    listenerPids: pids,
    sourceCommit: run('git', ['rev-parse', '--short', 'HEAD']) || 'unknown',
    sourceBranch: run('git', ['branch', '--show-current']) || 'unknown',
    apiAuthConfigured: Boolean(apiKey),
    login,
    runtimePayload,
    failurePayload,
  })
  const report = buildRestartProofReport(input)
  const text = JSON.stringify(report, null, 2)
  console.log(text)
  if (!report.ok) process.exit(1)
}

if (import.meta.url === `${['file', '://'].join('')}${process.argv[1]}`) {
  runCli()
}
